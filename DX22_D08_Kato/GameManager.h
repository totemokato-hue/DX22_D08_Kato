#pragma once

//＝＝＝インクルード＝＝＝

//＝＝＝定数・マクロ定義＝＝＝

//＝＝＝列挙型＝＝＝
// 現在のゲーム進行
enum class GameState
{
	PLAY,	// 実行
	CLEAR,	// ゲームクリア
	OVER	// ゲームオーバー
};

//＝＝＝クラス宣言＝＝＝
/**
* @brief	ゲーム進行に関するクラス
*/
class GameManager
{
public:
	//==================================================
	// コンストラクタ・デストラクタ
	//==================================================
	GameManager();	// コンストラクタ
	~GameManager();	// デストラクタ

	//==================================================
	// メンバー関数
	//==================================================
	/**
	* @brief	ゲームクリア状態にする
	*/
	void GameClear();

	/**
	* @brief	ゲームオーバー状態にする
	*/
	void GameOver();

	/**
	* @brief	状態を初期化する
	*/
	void Reset();

	/**
	* @brief	ゲームオーバーか判定する
	* @return	ゲームオーバーフラグ
	*/
	bool IsGameOver() const;

	/**
	* @brief	ゲームクリア判定
	* @return	ゲームクリアフラグ
	*/
	bool IsGameClear() const;

private:
	//==================================================
	// メンバー変数
	//==================================================
	GameState m_gameState;		// 現在のゲーム進行

};