#include "Geometory.h"

void Geometory::MakeBox()
{
	//--- 頂点の作成
	Vertex vtx[] = {
		//正面
		{{-0.5f,0.5f,-0.5f},{0.0f,0.0f}}, //0
		{{0.5f,0.5f,-0.5f},{1.0f,0.0f}},  //1
		{{-0.5f,-0.5f,-0.5f},{0.0f,1.0f}},//2
		{{0.5f,-0.5f,-0.5f},{1.0f,1.0f}}, //3
		//右面
		{{0.5f,0.5f,-0.5f},{0.0f,0.0f}},  //4
		{{0.5f,0.5f, 0.5f},{1.0f,0.0f}},  //5
		{{0.5f,-0.5f,-0.5f},{0.0f,1.0f}},  //6
		{{0.5f,-0.5f, 0.5f},{1.0f,1.0f}},  //7
		//後面
		{{0.5f,0.5f, 0.5f},{0.0f,0.0f}},  //8
		{{-0.5f,0.5f, 0.5f},{1.0f,0.0f}},  //9
		{{0.5f,-0.5f, 0.5f},{0.0f,1.0f}},  //10
		{{-0.5f,-0.5f, 0.5f},{1.0f,1.0f}},  //11
		//左面
		{{-0.5f,0.5f, 0.5f},{0.0f,0.0f}},  //12
		{{-0.5f,0.5f, -0.5f},{1.0f,0.0f}},  //13
		{{-0.5f,-0.5f, 0.5f},{0.0f,1.0f}},  //14
		{{-0.5f,-0.5f, -0.5f},{1.0f,1.0f}},  //15
		//上面
		{{0.5f,0.5f, 0.5f},{0.0f,0.0f}},  //16
		{{-0.5f,0.5f, 0.5f},{1.0f,0.0f}},  //17
		{{0.5f,0.5f, -0.5f},{0.0f,1.0f}},  //18
		{{-0.5f,0.5f, -0.5f},{1.0f,1.0f}},  //19
		//下面
		{{-0.5f,-0.5f, -0.5f},{1.0f,1.0f}},  //20
		{{0.5f,-0.5f, -0.5f},{1.0f,0.0f}},  //21
		{{-0.5f,-0.5f, 0.5f},{0.0f,1.0f}},  //22
		{{0.5f,-0.5f, 0.5f},{0.0f,0.0f}},  //23
	
	};
	//--- インデックスの作成
	int idx[] = {
		0,1,2,1,3,2,//前面
		4,5,6,5,7,6,//右面
		8,9,10,9,11,10,//裏面
		12,13,14,13,15,14,//左面
		18,17,16,18,19,17,//上面
		20,21,22,21,23,22//下面
	};
	// バッファの作成
	MeshBuffer::Description desc = {};
	desc.pVtx = vtx;//頂点のデータ
	desc.vtxCount = 24;
	desc.vtxSize = 20;
	desc.pIdx = idx;
	desc.idxCount = 36;
	desc.idxSize = 4;
	desc.topology = D3D11_PRIMITIVE_TOPOLOGY_TRIANGLELIST;
	m_pBox = new MeshBuffer;
	m_pBox->Create(desc);
}

